def bank_with_sources():
    rows = [json.loads(line) for line in (Path(__file__).resolve().parents[1] /
            "rag_data/chunks.jsonl").read_text().splitlines()]
    sources = {row["id"]: row for row in rows}
    for bank_item in PAIRS + CASE_PAIRS:
        for source in bank_item["source_ids"]:
            if source not in sources:
                raise ValueError(f"Missing assessment source: {source}")
    return sources
